"""Generates the Firestore TTL policy tables and commands of docs/07_deployment/README.md from config/ttl_registry.json.

Usage: python -m scripts.generate_ttl_runbook [--check]   (no flag rewrites the blocks between the markers; --check exits 1 on drift)
The registry is the one list; a policy is never hand-added to the README. Only `ttl-policy` entries get a policy command;
`unverified` ones are listed in the second block, after the prose about missing policies.
"""
import json
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "config" / "ttl_registry.json"
README = ROOT / "docs" / "07_deployment" / "README.md"
BEGIN = "<!-- ttl-runbook:begin (generated by scripts/generate_ttl_runbook.py from config/ttl_registry.json; do not edit) -->"
END = "<!-- ttl-runbook:end -->"
BEGIN_U = "<!-- ttl-unverified:begin (generated by scripts/generate_ttl_runbook.py from config/ttl_registry.json; do not edit) -->"
END_U = "<!-- ttl-unverified:end -->"
NUMBER_WORDS = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven", 8: "Eight", 9: "Nine"}


def group(entry: Dict) -> str:
    """The collection-group id as the runbook shows it: `<prefix>` in front unless the group is unprefixed."""
    return f"<prefix>{entry['collection']}" if entry.get("prefixed", True) else entry["collection"]


def _table(entries: List[Dict]) -> List[str]:
    rows = ["| Collection group | What expires |", "|---|---|"]
    for e in entries:
        if e.get("runbook_row") == "merged":
            continue
        label = f"`{group(e)}`"
        if e.get("runbook_also"):
            other = next(x for x in entries if x["id"] == e["runbook_also"])
            label += f" and `{group(other)}`"
        rows.append(f"| {label} | {e['what_expires']} |")
    return rows


def _command(field: str) -> List[str]:
    verb = "ttls " + "update"
    return ["```bash", f"gcloud firestore fields {verb} {field} --collection-group=<collection-group> \\",
            "  --enable-ttl --database=us-production --project=<PROJECT_ID>", "```"]


def render_block(entries: List[Dict]) -> str:
    policies = [e for e in entries if e["deleted_by"] == "ttl-policy"]
    expires = [e for e in policies if e["field"] == "expires_at"]
    purge = [e for e in policies if e["field"] == "purge_after"]
    count = NUMBER_WORDS.get(len(purge), str(len(purge)))
    lines = [BEGIN, ""] + _table(expires) + [""] + _command("expires_at") + [""]
    lines += [f"{count} collections expire on a different field, **`purge_after`**, which exists only in storage:", ""]
    lines += _table(purge) + [""] + _command("purge_after") + ["", END]
    return "\n".join(lines)


def render_unverified(entries: List[Dict]) -> str:
    unverified = [e for e in entries if e["deleted_by"] == "unverified"]
    lines = [BEGIN_U, "", "Collections whose code writes an expiry but whose policy is not in this runbook "
             "(owner: confirm one exists, or add it to the registry):", "", "| Collection | Field | Note |", "|---|---|---|"]
    lines += [f"| `{group(e)}` | `{e['field']}` | {e['note']} |" for e in unverified] + ["", END_U]
    return "\n".join(lines)


def apply(readme: str, block: str, unverified: str = "") -> str:
    """Replace the policy block (and, when given, the unverified block) between their markers."""
    for begin, end, text in ((BEGIN, END, block), (BEGIN_U, END_U, unverified)):
        if text:
            start, stop = readme.index(begin), readme.index(end) + len(end)
            readme = readme[:start] + text + readme[stop:]
    return readme


def main(argv: List[str]) -> int:
    entries = json.loads(REGISTRY.read_text(encoding="utf-8"))["entries"]
    text = README.read_text(encoding="utf-8")
    new = apply(text, render_block(entries), render_unverified(entries))
    if "--check" in argv:
        if new != text:
            print("docs/07_deployment/README.md differs from config/ttl_registry.json: run python -m scripts.generate_ttl_runbook")
            return 1
        return 0
    README.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
