"""Generates the Firestore TTL policy tables and commands of docs/07_deployment/README.md from config/ttl_registry.json.

Usage: python -m scripts.generate_ttl_runbook [--check]   (no flag rewrites the block between the markers; --check exits 1 on drift)
The registry is the one list; a policy is never hand-added to the README. Only `ttl-policy` entries get a policy command; `unverified` ones are listed under it.
"""
import json
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "config" / "ttl_registry.json"
README = ROOT / "docs" / "07_deployment" / "README.md"
BEGIN = "<!-- ttl-runbook:begin (generated by scripts/generate_ttl_runbook.py from config/ttl_registry.json; do not edit) -->"
END = "<!-- ttl-runbook:end -->"


def _table(entries: List[Dict]) -> List[str]:
    rows = ["| Collection group | What expires |", "|---|---|"]
    rows += [f"| `<prefix>{e['collection']}` | {e['what_expires']} |" for e in entries]
    return rows


def _command(field: str) -> List[str]:
    return ["```bash", f"gcloud firestore fields ttls update {field} --collection-group=<collection-group> \\",
            "  --enable-ttl --database=us-production --project=<PROJECT_ID>", "```"]


def render_block(entries: List[Dict]) -> str:
    policies = [e for e in entries if e["deleted_by"] == "ttl-policy"]
    expires = [e for e in policies if e["field"] == "expires_at"]
    purge = [e for e in policies if e["field"] == "purge_after"]
    lines = [BEGIN, ""] + _table(expires) + [""] + _command("expires_at") + [""]
    lines += ["The collections below expire on a different field, **`purge_after`**, which exists only in storage:", ""]
    lines += _table(purge) + [""] + _command("purge_after") + [""]
    unverified = [e for e in entries if e["deleted_by"] == "unverified"]
    lines += ["Collections whose code writes an expiry but whose policy is not in this runbook (owner: confirm one exists, or add it to the registry):", ""]
    lines += ["| Collection | Field | Note |", "|---|---|---|"]
    lines += [f"| `<prefix>{e['collection']}` | `{e['field']}` | {e['note']} |" for e in unverified] + ["", END]
    return "\n".join(lines)


def apply(readme: str, block: str) -> str:
    start, stop = readme.index(BEGIN), readme.index(END) + len(END)
    return readme[:start] + block + readme[stop:]


def main(argv: List[str]) -> int:
    entries = json.loads(REGISTRY.read_text(encoding="utf-8"))["entries"]
    text = README.read_text(encoding="utf-8")
    new = apply(text, render_block(entries))
    if "--check" in argv:
        if new != text:
            print("docs/07_deployment/README.md differs from config/ttl_registry.json: run python -m scripts.generate_ttl_runbook")
            return 1
        return 0
    README.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
