# Kinds of site: `skipif`, `mark.skip`, `skip` (a runtime pytest.skip), `importorskip`, `marker`.
Site = Tuple[str, str, str]          # (path relative to the repo root, kind, condition)


@dataclass(frozen=True)
class Rule:
    """The gate and the reason of every site whose kind, path and condition match. First match wins."""
    kind: str
    path: str
    condition: str
    gate: str
    reason: str

    def matches(self, site: Site) -> bool:
        path, kind, condition = site
        return (re.fullmatch(self.kind, kind) is not None and re.search(self.path, path) is not None
                and re.fullmatch(self.condition, condition, re.S) is not None)


def _r(kind: str, path: str, condition: str, gate: str, reason: str) -> Rule:
    return Rule(kind, path, condition, gate, reason)


