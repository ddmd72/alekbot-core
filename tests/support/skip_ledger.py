def _condition(node: ast.Call, kind: str) -> str:
    keywords = {k.arg: k.value for k in node.keywords if k.arg}
    if kind == "skipif":
        target = node.args[0] if node.args else keywords.get("condition")
        return ast.unparse(target) if target is not None else ""
    if kind == "mark.skip":
        if node.args:
            return ast.unparse(node.args[0])
        return f"reason={ast.unparse(keywords['reason'])}" if "reason" in keywords else ""
    target = node.args[0] if node.args else keywords.get("reason") or keywords.get("modname")
    return ast.unparse(target) if target is not None else ""


def _aliases(tree: ast.AST) -> Dict[str, str]:
    """Local names bound to pytest / unittest things: `import pytest as pt`, `from pytest import skip, mark`."""
    names: Dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] in ("pytest", "unittest"):
                    names[alias.asname or alias.name.split(".")[0]] = alias.name if alias.asname else alias.name.split(".")[0]
        elif isinstance(node, ast.ImportFrom) and node.module and node.module.split(".")[0] in ("pytest", "unittest") and node.level == 0:
            for alias in node.names:
                names[alias.asname or alias.name] = f"{node.module}.{alias.name}"
    return names


def _canonical(node: ast.AST, aliases: Dict[str, str]) -> str:
    """The dotted name of a Name / Attribute chain with its root resolved through the imports ('' when it is neither)."""
    parts: List[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if not isinstance(node, ast.Name):
        return ""
    root = aliases.get(node.id)
    if root is None:
        return ""
    return ".".join([root] + parts[::-1])


def _kind(canonical: str) -> Optional[str]:
    last = canonical.rsplit(".", 1)[-1]
    if last in ("skipif", "skipIf", "skipUnless"):
        return "skipif"
    if last == "skip":
        return "skip" if canonical == "pytest.skip" else "mark.skip"
    if last in ("importorskip",):
        return "importorskip"
    if last == "SkipTest":
        return "skip"
    return None


def _is_test(node: ast.AST) -> bool:
    return isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test")


def _tests_in(scope: ast.AST) -> int:
    return sum(1 for node in ast.walk(scope) if _is_test(node))


def scan_source(path: str, source: str) -> List[Site]:
    """The skip sites of one file, one entry per test the site affects (a repeated site repeats).

    A skip on a test function counts that test; on a class, the tests in the class; assigned to a module- or class-level name, the
    uses of the name (a decorator, an entry of `pytestmark`); inside `pytestmark`, the tests of the module or class. A runtime
    `pytest.skip(...)` counts once wherever it is called, so one inside a fixture or helper under-counts the tests behind it.
    """
    tree = ast.parse(source)
    aliases = _aliases(tree)
    parents = {child: node for node in ast.walk(tree) for child in ast.iter_child_nodes(node)}
    call_funcs = {id(node.func) for node in ast.walk(tree) if isinstance(node, ast.Call)}

    def weight_of_use(node: ast.AST) -> int:
        """Tests behind an expression that is a decorator or an entry of `pytestmark`; 1 elsewhere."""
        child = node
        while child in parents:
            parent = parents[child]
            if isinstance(parent, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                if child in parent.decorator_list:
                    return _tests_in(parent) if isinstance(parent, ast.ClassDef) else 1
                return 1
            if isinstance(parent, (ast.Assign, ast.AnnAssign)):
                targets = parent.targets if isinstance(parent, ast.Assign) else [parent.target]
                if any(isinstance(t, ast.Name) and t.id == "pytestmark" for t in targets):
                    scope = parents.get(parent)
                    return max(1, _tests_in(scope)) if scope is not None else 1
                return 1
            child = parent
        return 1

    def weight(node: ast.AST) -> int:
        child = node
        while child in parents:
            parent = parents[child]
            if isinstance(parent, (ast.Assign, ast.AnnAssign)) and isinstance(parents.get(parent), (ast.Module, ast.ClassDef)):
                targets = parent.targets if isinstance(parent, ast.Assign) else [parent.target]
                names = [t.id for t in targets if isinstance(t, ast.Name)]
                if names and names[0] != "pytestmark":
                    uses = [use for use in ast.walk(parents[parent]) if isinstance(use, ast.Name) and use.id == names[0]
                            and isinstance(use.ctx, ast.Load)]
                    return max(1, sum(weight_of_use(use) for use in uses))
            if isinstance(parent, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Assign, ast.AnnAssign)):
                return weight_of_use(node)
            child = parent
        return 1

    sites: List[Site] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            canonical = _canonical(node.func, aliases)
            kind = _kind(canonical) if canonical.split(".")[0] in ("pytest", "unittest") else None
            if kind:
                condition = " ".join(_condition(node, kind).split()) or "<bare>"
                sites.extend([(path, kind, condition)] * weight(node))
        elif isinstance(node, (ast.Attribute, ast.Name)):
            canonical = _canonical(node, aliases)
            if canonical.startswith("pytest.mark.") and canonical.rsplit(".", 1)[-1] in MARKERS:
                sites.append((path, "marker", canonical.rsplit(".", 1)[-1]))
            elif canonical in ("pytest.mark.skip", "unittest.skip") and id(node) not in call_funcs:
                sites.extend([(path, "mark.skip", "<bare>")] * weight(node))
    return sites


def scan_tree(root: Path = REPO_ROOT, tests: str = "tests") -> Dict[Site, int]:
    """Every skip site under `root/tests`, counted; a marker counts once per file."""
    counts: Dict[Site, int] = {}
    for file in sorted((root / tests).rglob("*.py")):
        rel = file.relative_to(root).as_posix()
        for site in scan_source(rel, file.read_text(encoding="utf-8")):
            counts[site] = 1 if site[1] == "marker" else counts.get(site, 0) + 1
    return counts


def classify(site: Site, rules: Sequence[Rule] = RULES) -> Optional[Rule]:
    return next((rule for rule in rules if rule.matches(site)), None)


def unused_rules(sites: Iterable[Site], rules: Sequence[Rule] = RULES) -> List[Rule]:
    """Rules that classify no site: a rule whose subject is gone is stale and goes."""
    sites = list(sites)
    return [rule for rule in rules if not any(classify(site, rules) is rule for site in sites)]


def render_line(site: Site, count: int, rule: Rule) -> str:
    path, kind, condition = site
    left = f"{path} :: {kind} :: {condition}" + ("" if kind == "marker" else f" :: x{count}")
    return f"{left}  # {rule.gate}: {rule.reason}"


def render(counts: Dict[Site, int], rules: Sequence[Rule] = RULES) -> str:
    lines = []
    for site, count in counts.items():
        rule = classify(site, rules)
        lines.append(render_line(site, count, rule) if rule else f"{site[0]} :: {site[1]} :: {site[2]}  # unclassified")
    return HEADER + "\n".join(sorted(lines)) + "\n"


def parse_ledger(text: str) -> Dict[Site, Tuple[int, str, str]]:
    """The ledger's lines as {site: (count, gate, reason)}; a malformed line raises ValueError."""
    parsed: Dict[Site, Tuple[int, str, str]] = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        left, sep, tail = line.rpartition("  # ")
        gate, colon, reason = tail.partition(": ")
        if not sep or not colon:
            raise ValueError(f"line {number}: expected `<site>  # <gate>: <reason>`")
        parts = left.split(" :: ", 2)
        if len(parts) != 3:
            raise ValueError(f"line {number}: expected `<path> :: <kind> :: <condition>`")
        path, kind, rest = parts
        count = 1
        if kind != "marker":
            match = re.fullmatch(r"(.*) :: x(\d+)", rest, re.S)
            if not match:
                raise ValueError(f"line {number}: a non-marker line ends with `:: x<count>`")
            rest, count = match.group(1), int(match.group(2))
        site = (path, kind, rest)
        if site in parsed:
            raise ValueError(f"line {number}: duplicate site")
        parsed[site] = (count, gate, reason)
    return parsed


def diff(counts: Dict[Site, int], ledger: Dict[Site, Tuple[int, str, str]], rules: Sequence[Rule] = RULES) -> List[str]:
    """Both ways: a site the ledger lacks, a ledger line whose site is gone, a count, gate or reason that differs."""
    problems: List[str] = []
    for site in sorted(set(counts) - set(ledger)):
        problems.append(f"skip site not in the ledger: {site[0]} :: {site[1]} :: {site[2]}")
    for site in sorted(set(ledger) - set(counts)):
        problems.append(f"ledger line whose skip site is gone: {site[0]} :: {site[1]} :: {site[2]}")
    for site in sorted(set(counts) & set(ledger)):
        count, gate, reason = ledger[site]
        rule = classify(site, rules)
        if rule is None:
            problems.append(f"no rule classifies: {site[0]} :: {site[1]} :: {site[2]}")
            continue
        if count != counts[site]:
            problems.append(f"count differs ({count} in the ledger, {counts[site]} in the tree): {site[0]} :: {site[1]} :: {site[2]}")
        if (gate, reason) != (rule.gate, rule.reason):
            problems.append(f"gate or reason differs from its rule: {site[0]} :: {site[1]} :: {site[2]}")
    return problems


def never_lines(ledger: Dict[Site, Tuple[int, str, str]]) -> List[Site]:
    return sorted(site for site, (_, gate, _reason) in ledger.items() if gate == "never")
