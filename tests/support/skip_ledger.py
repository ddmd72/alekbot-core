"""The skip ledger (TEST_COVERAGE_SYSTEMIC_RFC P22): every place under `tests/` that can make a test not run, and the gate that runs it.

A test that is skipped everywhere is a test nobody runs: the suite stays green while the behaviour it pins is
unwatched. This module finds each skip site by AST (`skipif`, `mark.skip`, `pytest.skip(...)`, `importorskip`, and
unittest's `skip` / `skipIf` / `skipUnless` / `SkipTest`, and the `slow` / `timing` / `docker` / `performance` markers; the conftest
turns only `slow` and `timing` into a skip by a switch, the other two skip through their own `skipif` or not at all), classifies it
by the gate that runs it, and renders one sorted line per site for `tests/skip_ledger.txt`.

Gates: `ci` runs in the CI `check` job (its prerequisite is on the runner), `ci-slow` runs in `make ci` (RUN_SLOW_TESTS=1),
`timing` runs in `make test-timing` (CI job `timing`, after a merge to main), `render-job` runs in the post-merge workflow
`render.yml` (job `render`: node modules and chrome-headless-shell installed; job `sandbox-image`: the built sandbox images),
`widget-job` runs in the workflow `widget_renderer.yml` (job `widget-renderer`: Playwright Chromium installed; on a PR that
touches the renderer, its tests or requirements.txt, and by hand), `cloud` runs in `make test-cloud`
(weekly `Firestore parity`), `param` is a case of a parametrised or contract test that does not apply to one backend
(the other cases run), `manual` runs only when the owner starts it by hand (a make target, an emulator, the Mac) and
`never` has no gate and no job that prepares its prerequisite. Every line carries a reason; `never` is the list the
owner's decisions work down.

A line is `<path> :: <kind> :: <condition> :: x<count>  # <gate>: <reason>`; a marker line has no count (a file
either holds the marker or not, so adding a slow test to a file that has one changes nothing). `x<count>` is the number of tests
the site affects: a decorator on a test is one, on a class the tests of the class, a skip assigned to a name the uses of the name
(a decorator, an entry of `pytestmark`), a `pytestmark` the tests of its module or class. LIMIT: a runtime `pytest.skip(...)`
counts once wherever it is called, so one in a fixture or a helper under-counts the tests behind it, and a test with
parametrize counts once whatever its cases. Not seen: `self.skipTest(...)` and a skip reached through a name from another module.
"""
